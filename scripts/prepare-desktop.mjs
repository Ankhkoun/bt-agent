import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(join(root, 'desktop/package.json'));
const { Resvg } = require('@resvg/resvg-js');
const toIco = require('to-ico');
const source = readFileSync(join(root, 'desktop/public/bt-logo.svg'), 'utf8');
const png = new Resvg(source).render().asPng();
const ico = await toIco(png);
for (const path of ['desktop/public/icon.png', 'desktop/public/icon-mac.png', 'desktop/electron/tray-icon.png', 'desktop/app/icon.png']) writeFileSync(join(root, path), png);
for (const path of ['desktop/public/icon.ico', 'desktop/app/icon.ico']) writeFileSync(join(root, path), ico);
for (const path of ['desktop/public/favicon.svg', 'desktop/app/favicon.svg', 'desktop/app/icon.svg']) writeFileSync(join(root, path), source);
const splashPath = join(root, 'desktop/public/splash.html');
let splash = readFileSync(splashPath, 'utf8').replaceAll('30141', '30142').replaceAll('Pi Agent Web', 'BT-Agent');
splash = splash.replace(/<svg[\s\S]*?<\/svg>/, source);
writeFileSync(splashPath, splash);
const layoutPath = join(root, 'desktop/app/layout.tsx');
let layout = readFileSync(layoutPath, 'utf8');
layout = layout.replace('if(wpe!=="0")', 'if(wpe==="1")');
const bootstrap = 'if(!localStorage.getItem("pi-locale"))localStorage.setItem("pi-locale","zh-CN");if(!localStorage.getItem("pi-recent-projects-enabled"))localStorage.setItem("pi-recent-projects-enabled","0");';
if (!layout.includes(bootstrap)) layout = layout.replace('(function(){try{var h=', `(function(){try{${bootstrap}var h=`);
writeFileSync(layoutPath, layout);
console.log('BT desktop icons and first-run defaults prepared.');
